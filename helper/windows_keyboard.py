"""Windows keyboard hook. Retains only shortcut-related key state."""
import ctypes
from ctypes import wintypes
import queue
import threading
import time
from shortcuts import Gesture, parse_shortcut


INPUT_TAG = 0x53415247


class KeyboardHook:
    def __init__(self, shortcut, events, generation):
        self.modifiers, self.key = parse_shortcut(shortcut)
        self.events = events
        self.generation = generation
        self.gesture = Gesture()
        self.pressed = set()
        self.active = False
        self.swallowed = False
        self.commands = queue.SimpleQueue()
        self.ready = threading.Event()
        self.error = None
        self.thread = threading.Thread(target=self._run, daemon=True)
        self.thread_id = None

    def start(self):
        self.thread.start()
        if not self.ready.wait(3) or self.error:
            raise RuntimeError('Windows keyboard access is unavailable')

    def reset(self):
        self.commands.put('reset')

    def stop(self):
        if self.thread_id:
            ctypes.windll.user32.PostThreadMessageW(self.thread_id, 0x0012, 0, 0)
        self.thread.join(timeout=2)

    def _emit(self, events):
        for event in events:
            self.events.put(('gesture', (self.generation, event)))

    def _run(self):
        user32 = ctypes.WinDLL('user32', use_last_error=True)
        kernel32 = ctypes.WinDLL('kernel32', use_last_error=True)
        pointer_int = ctypes.c_ssize_t
        callback_type = ctypes.WINFUNCTYPE(pointer_int, ctypes.c_int, wintypes.WPARAM, wintypes.LPARAM)

        class KeyData(ctypes.Structure):
            _fields_ = [('vkCode', wintypes.DWORD), ('scanCode', wintypes.DWORD), ('flags', wintypes.DWORD),
                        ('time', wintypes.DWORD), ('dwExtraInfo', ctypes.c_size_t)]

        user32.SetWindowsHookExW.argtypes = [ctypes.c_int, callback_type, wintypes.HINSTANCE, wintypes.DWORD]
        user32.SetWindowsHookExW.restype = wintypes.HHOOK
        user32.CallNextHookEx.argtypes = [wintypes.HHOOK, ctypes.c_int, wintypes.WPARAM, wintypes.LPARAM]
        user32.CallNextHookEx.restype = pointer_int
        user32.UnhookWindowsHookEx.argtypes = [wintypes.HHOOK]
        user32.SetTimer.argtypes = [wintypes.HWND, ctypes.c_size_t, wintypes.UINT, ctypes.c_void_p]
        user32.SetTimer.restype = ctypes.c_size_t
        user32.KillTimer.argtypes = [wintypes.HWND, ctypes.c_size_t]
        kernel32.GetModuleHandleW.argtypes = [wintypes.LPCWSTR]
        kernel32.GetModuleHandleW.restype = wintypes.HMODULE

        modifier_codes = {'Control': {0x11, 0xA2, 0xA3}, 'Alt': {0x12, 0xA4, 0xA5},
                          'Shift': {0x10, 0xA0, 0xA1}, 'Win': {0x5B, 0x5C}}
        tracked = set().union(*modifier_codes.values(), {self.key})

        def callback(code, message, data_pointer):
            if code < 0:
                return user32.CallNextHookEx(None, code, message, data_pointer)
            data = ctypes.cast(data_pointer, ctypes.POINTER(KeyData)).contents
            if data.dwExtraInfo == INPUT_TAG:  # Ignore only input generated by Sargosh itself.
                return user32.CallNextHookEx(None, code, message, data_pointer)
            vk = data.vkCode
            if vk not in tracked:
                return user32.CallNextHookEx(None, code, message, data_pointer)
            down = message in (0x0100, 0x0104)
            up = message in (0x0101, 0x0105)
            if not down and not up:
                return user32.CallNextHookEx(None, code, message, data_pointer)
            if down:
                self.pressed.add(vk)
            else:
                self.pressed.discard(vk)
            current_modifiers = {name for name, keys in modifier_codes.items() if self.pressed & keys}
            chord = self.key in self.pressed and current_modifiers == self.modifiers
            if chord and not self.active and down and vk == self.key:
                self.active = True
                self.swallowed = True
                self._emit(self.gesture.press(time.monotonic()))
            elif not chord and self.active:
                self.active = False
                self._emit(self.gesture.release(time.monotonic()))
            consume = vk == self.key and self.swallowed
            if vk == self.key and up:
                self.swallowed = False
            return 1 if consume else user32.CallNextHookEx(None, code, message, data_pointer)

        self.callback = callback_type(callback)
        hook = None
        timer = 0
        try:
            self.thread_id = kernel32.GetCurrentThreadId()
            # Initialize this thread's message queue before announcing readiness.
            message = wintypes.MSG()
            user32.PeekMessageW(ctypes.byref(message), None, 0, 0, 0)
            hook = user32.SetWindowsHookExW(13, self.callback, kernel32.GetModuleHandleW(None), 0)
            if not hook:
                raise ctypes.WinError(ctypes.get_last_error())
            timer = user32.SetTimer(None, 0, 20, None)
            if not timer:
                raise ctypes.WinError(ctypes.get_last_error())
            self.ready.set()
            while True:
                result = user32.GetMessageW(ctypes.byref(message), None, 0, 0)
                if result <= 0:
                    break
                if message.message == 0x0113:
                    while not self.commands.empty():
                        command = self.commands.get()
                        self.gesture.reset()
                        if command == 'hands-free':
                            self.gesture.state = 'hands-free'
                    self._emit(self.gesture.tick(time.monotonic()))
                user32.TranslateMessage(ctypes.byref(message))
                user32.DispatchMessageW(ctypes.byref(message))
        except Exception:
            self.error = 'Windows keyboard access is unavailable'
            self.ready.set()
        finally:
            if timer:
                user32.KillTimer(None, timer)
            if hook:
                user32.UnhookWindowsHookEx(hook)
            self.thread_id = None
